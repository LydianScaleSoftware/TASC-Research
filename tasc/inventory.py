"""Extract every file from the TASC images and record hash, type, address, length.

    python -m tasc.inventory            # writes extracted/<image>/ and docs/inventory.md
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from tasc import disk

ROOT = Path(__file__).resolve().parent.parent
IMAGES = {
    "tasc201": "TASC 2.01 (Microsoft 1981).dsk",
    "tasc20": "TASC 2.0 (Microsoft 1981).dsk",
    "asimov20": "tasc-compiler.dsk",
    "rebuild": "TASC COMPILER.DSK",
}
TYPE_NAMES = {0x04: "TXT", 0x06: "BIN", 0xFA: "INT", 0xFC: "BAS"}


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def main() -> None:
    rows: dict[str, list[dict[str, object]]] = {}
    for key, fname in IMAGES.items():
        img = ROOT / "images" / "original" / fname
        outdir = ROOT / "extracted" / key
        outdir.mkdir(parents=True, exist_ok=True)
        rows[key] = []
        files = disk.extract_all(img)
        for ent in disk.catalog(img):
            f = files[ent.name]
            safe = ent.name.replace("/", "_").replace(" ", "_")
            (outdir / f"{safe}#{f.ftype:02x}{f.aux:04x}").write_bytes(f.data)
            rows[key].append(
                {
                    "name": ent.name,
                    "type": TYPE_NAMES.get(f.ftype, f"${f.ftype:02X}"),
                    "addr": f"${f.aux:04X}",
                    "length": len(f.data),
                    "sha256": sha(f.data),
                }
            )
    (ROOT / "extracted" / "inventory.json").write_text(json.dumps(rows, indent=1) + "\n")

    lines = ["# File inventory", "", "Generated by `python -m tasc.inventory`. SHA-256 of exact file data (no DOS header).", ""]
    for key, fname in IMAGES.items():
        lines += [f"## {key}: `{fname}`", "", "| File | Type | Addr | Length | SHA-256 (first 16) |", "|---|---|---|---|---|"]
        for r in rows[key]:
            lines.append(f"| {r['name']} | {r['type']} | {r['addr']} | {r['length']} | `{str(r['sha256'])[:16]}` |")
        lines.append("")
    # cross-image comparison of the compiler files
    lines += ["## Cross-image comparison", "", "| File | " + " | ".join(IMAGES) + " |", "|---|" + "---|" * len(IMAGES)]
    for nm in ["PASS0", "PASS1", "PASS2", "RUNTIME"]:
        cells = []
        for key in IMAGES:
            hit = [r for r in rows[key] if str(r["name"]) in (nm, nm + ".OBJ")]
            cells.append(f"`{str(hit[0]['sha256'])[:8]}` {hit[0]['length']}" if hit else "-")
        lines.append(f"| {nm} | " + " | ".join(cells) + " |")
    (ROOT / "docs" / "inventory.md").write_text("\n".join(lines) + "\n")
    print(f"extracted {sum(len(v) for v in rows.values())} files; see docs/inventory.md")


if __name__ == "__main__":
    main()
