"""Phase 0 end-to-end loop, no manual steps.

    python -m tasc.phase0

1. Extract and hash every file on the four images (tasc.inventory).
2. Detokenize the small Applesoft programs (launchers, CREATE ADR, BALL...).
3. Session A (fresh boot of the 2.01 work image): compile BALL with defaults,
   capture the listing and line-number table, BLOAD RUNTIME / BRUN BALL.OBJ,
   check that it runs and exits, then RUN HELLO and compile BALL again
   (run C: dirty memory, BALL.OBJ already on disk).
4. Session B (fresh boot): compile BALL again.
5. Compare A, B, C (object file and CLINENUM) and write experiments/phase0/summary.md.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from tasc import disk, inventory
from tasc.emu import Pandowdy, run_capturing
from tasc.harness import CompileError, Session, collect, compile_file, compile_in_session, sha256

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "images" / "work" / "tasc201.dsk"
OUT = ROOT / "experiments" / "phase0"


def detokenize_all() -> int:
    outdir = ROOT / "src" / "launchers"
    outdir.mkdir(parents=True, exist_ok=True)
    n = 0
    for key, fname in inventory.IMAGES.items():
        img = ROOT / "images" / "original" / fname
        for e in disk.catalog(img):
            if e.ftype != "A" or e.length > 1200 or "/" in e.name:
                continue
            text = disk.export_text(img, "bas", e.name)
            (outdir / f"{key}.{e.name.replace(' ', '_')}.bas.txt").write_text(text)
            n += 1
    return n


def run_ball(s: Session) -> dict[str, object]:
    """From the ] prompt: BLOAD RUNTIME, BRUN BALL.OBJ with 3 balls, then exit."""
    emu = s.emu
    emu.type("BLOAD RUNTIME\nBRUN BALL.OBJ\n")
    s.run_to_key(30_000_000)
    s.expect("HOW MANY BALLS")
    emu.type("3\n")
    run_capturing(emu, s.transcript, 10_000_000, stop_on_key_wait=False)
    scr = str(emu.call("read_text_screen"))
    rows = emu.screen_rows()
    lores = "lores" in scr
    prompt_ok = rows[23].startswith("PRESS ANY KEY TO EXIT-")
    pixels = sum(1 for r in rows[:20] for ch in r if ch != "@")
    emu.call("press_key", key="space")
    s.run_to_key(10_000_000)
    rows = emu.screen_rows()
    back = any(r.startswith("]") for r in rows) and "display mode: text" in str(emu.call("read_text_screen"))
    return {"lores_mode": lores, "exit_prompt": prompt_ok, "nonblack_cells": pixels, "returned_to_basic": back}


def main() -> None:
    inventory.main()
    print(f"detokenized {detokenize_all()} Applesoft programs into src/launchers/")

    results: dict[str, dict[str, object]] = {}

    # Session A, then C in the same machine
    a_dir, c_dir = OUT / "A_fresh", OUT / "C_same_session"
    for d in (a_dir, c_dir):
        shutil.rmtree(d, ignore_errors=True)
        d.mkdir(parents=True)
    shutil.copyfile(BASE, a_dir / "work.dsk")
    with Pandowdy() as emu:
        emu.boot(a_dir / "work.dsk")
        s = Session(emu)
        s.run_to_key(40_000_000)
        cyc = compile_in_session(s, "BALL")
        s.finish_transcript()
        emu.call("save_disk", path=str((a_dir / "after.dsk").resolve()))
        ra = collect(a_dir, "BALL", s.transcript, cyc)
        ball_run = run_ball(s)

        s.transcript.rows.clear()
        emu.type("RUN HELLO\n")
        s.run_to_key(40_000_000)
        cyc = compile_in_session(s, "BALL")
        s.finish_transcript()
        emu.call("save_disk", path=str((c_dir / "after.dsk").resolve()))
        rc = collect(c_dir, "BALL", s.transcript, cyc)

    # Session B
    b_dir = OUT / "B_fresh"
    shutil.rmtree(b_dir, ignore_errors=True)
    rb = compile_file(BASE, "BALL", b_dir)

    def clinenum(d: Path) -> str:
        p = d / "CLINENUM"
        return sha256(p.read_bytes()) if p.exists() else "-"

    for name, r, d in (("A", ra, a_dir), ("B", rb, b_dir), ("C", rc, c_dir)):
        results[name] = {
            "obj_sha256": r.obj_sha256,
            "obj_addr": f"${r.obj_addr:04X}",
            "obj_len": r.obj_len,
            "clinenum_sha256": clinenum(d),
            "cycles": r.cycles,
            "lines_in_table": len(r.line_table),
        }
    same_obj = len({str(v["obj_sha256"]) for v in results.values()}) == 1
    same_tab = ra.line_table == rb.line_table == rc.line_table
    same_cl = len({str(v["clinenum_sha256"]) for v in results.values()}) == 1
    summary = {
        "runs": results,
        "deterministic_obj": same_obj,
        "deterministic_line_table": same_tab,
        "deterministic_clinenum": same_cl,
        "ball_run": ball_run,
        "info": ra.info,
    }
    (OUT / "summary.json").write_text(json.dumps(summary, indent=1) + "\n")

    md = ["# Phase 0 summary", "", "Generated by `python -m tasc.phase0`.", "",
          "| Run | Object SHA-256 | Addr | Len | CLINENUM | Cycles | Table lines |", "|---|---|---|---|---|---|---|"]
    for k, v in results.items():
        md.append(f"| {k} | `{str(v['obj_sha256'])[:16]}` | {v['obj_addr']} | {v['obj_len']} | `{str(v['clinenum_sha256'])[:8]}` | {v['cycles']:,} | {v['lines_in_table']} |")
    md += ["", f"- Object files identical: **{same_obj}**; line tables identical: **{same_tab}**; CLINENUM identical: **{same_cl}**",
           f"- BALL.OBJ run: {ball_run}", f"- Compile info: {ra.info}", "",
           "A = fresh boot; B = second fresh boot; C = same machine as A after running BALL.OBJ,",
           "RUN HELLO, recompiling over the existing BALL.OBJ.", ""]
    md += ["## Line-number table (run A)", "", "| Line | Addr | Hex |", "|---|---|---|"]
    md += [f"| {e.line} | {e.addr} | ${e.addr:04X} |" for e in ra.line_table]
    (OUT / "summary.md").write_text("\n".join(md) + "\n")

    print(f"A/B/C object identical={same_obj} table identical={same_tab} CLINENUM identical={same_cl}")
    print(f"BALL.OBJ ${ra.obj_addr:04X} len {ra.obj_len} sha {ra.obj_sha256[:16]}  run: {ball_run}")
    if not (same_obj and same_tab and all(ball_run.values())):
        raise CompileError("Phase 0 checks failed; see experiments/phase0/summary.md")


if __name__ == "__main__":
    main()
